-- YouTube Transcript RAG foundation schema.
-- This file is intentionally safe to rerun on the same schema.

create extension if not exists vector with schema extensions;

create table if not exists public.videos (
  id bigint generated by default as identity primary key,
  youtube_id text not null,
  title text,
  status text not null default 'pending',
  error_message text,
  ingestion_token uuid,
  ingestion_started_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint videos_youtube_id_key unique (youtube_id),
  constraint videos_youtube_id_format_check
    check (youtube_id ~ '^[A-Za-z0-9_-]{11}$'),
  constraint videos_status_check
    check (status in ('pending', 'ready', 'failed')),
  constraint videos_error_state_check
    check (
      (status = 'failed' and error_message is not null)
      or (status <> 'failed' and error_message is null)
    ),
  constraint videos_ingestion_state_check
    check (
      (
        status = 'pending'
        and ingestion_token is not null
        and ingestion_started_at is not null
      )
      or (
        status in ('ready', 'failed')
        and ingestion_token is null
        and ingestion_started_at is null
      )
    )
);

create table if not exists public.documents (
  id bigint generated by default as identity primary key,
  content text not null,
  metadata jsonb not null,
  embedding extensions.vector(384) not null,
  created_at timestamptz not null default now(),
  constraint documents_content_check check (btrim(content) <> ''),
  constraint documents_metadata_object_check
    check (jsonb_typeof(metadata) = 'object'),
  constraint documents_video_id_metadata_check
    check (
      metadata ? 'video_id'
      and (metadata ->> 'video_id') ~ '^[1-9][0-9]*$'
    ),
  constraint documents_ingestion_metadata_check
    check (
      metadata ?& array[
        'youtube_id',
        'start',
        'ingestion_token',
        'chunk_index'
      ]
      and (metadata ->> 'youtube_id') ~ '^[A-Za-z0-9_-]{11}$'
      and jsonb_typeof(metadata -> 'start') = 'number'
      and (metadata ->> 'start')::numeric >= 0
      and (metadata ->> 'ingestion_token')
        ~ '^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$'
      and jsonb_typeof(metadata -> 'chunk_index') = 'number'
      and (metadata ->> 'chunk_index') ~ '^[0-9]+$'
    )
);

create table if not exists public.chat_messages (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  video_id bigint not null references public.videos(id) on delete cascade,
  role text not null,
  content text not null,
  created_at timestamptz not null default now(),
  constraint chat_messages_role_check
    check (role in ('user', 'assistant')),
  constraint chat_messages_content_check check (btrim(content) <> '')
);

create index if not exists documents_metadata_gin_idx
  on public.documents using gin (metadata);

create index if not exists documents_video_id_idx
  on public.documents (((metadata ->> 'video_id')::bigint));

create unique index if not exists documents_ingestion_chunk_idx
  on public.documents (
    (metadata ->> 'ingestion_token'),
    ((metadata ->> 'chunk_index')::integer)
  );

create index if not exists chat_messages_user_video_created_idx
  on public.chat_messages (user_id, video_id, created_at, id);

create index if not exists chat_messages_video_id_idx
  on public.chat_messages (video_id);

create or replace function public.match_documents(
  query_embedding extensions.vector(384),
  match_video_id bigint,
  match_count integer default 4
)
returns table (
  id bigint,
  content text,
  metadata jsonb,
  similarity double precision
)
language sql
stable
security invoker
set search_path = ''
as $function$
  select
    document.id,
    document.content,
    document.metadata,
    1 - (
      document.embedding
      operator(extensions.<=>)
      query_embedding
    ) as similarity
  from public.documents as document
  where (document.metadata ->> 'video_id')::bigint = match_video_id
  order by
    document.embedding
    operator(extensions.<=>)
    query_embedding
  limit least(greatest(coalesce(match_count, 4), 1), 50);
$function$;

create or replace function public.claim_video_ingestion(
  requested_youtube_id text,
  stale_after_seconds integer default 900
)
returns table (
  id bigint,
  youtube_id text,
  title text,
  status text,
  error_message text,
  created_at timestamptz,
  updated_at timestamptz,
  ingestion_token uuid,
  acquired boolean
)
language plpgsql
volatile
security invoker
set search_path = ''
as $function$
declare
  attempt_token uuid := extensions.gen_random_uuid();
  claimed public.videos%rowtype;
  lease_seconds integer := least(
    greatest(coalesce(stale_after_seconds, 900), 60),
    3600
  );
begin
  insert into public.videos as existing (
    youtube_id,
    status,
    error_message,
    ingestion_token,
    ingestion_started_at,
    updated_at
  )
  values (
    requested_youtube_id,
    'pending',
    null,
    attempt_token,
    now(),
    now()
  )
  on conflict on constraint videos_youtube_id_key do update
  set
    status = 'pending',
    error_message = null,
    ingestion_token = attempt_token,
    ingestion_started_at = now(),
    updated_at = now()
  where
    existing.status = 'failed'
    or (
      existing.status = 'pending'
      and existing.ingestion_started_at
        < now() - lease_seconds * interval '1 second'
    )
  returning existing.* into claimed;

  if found then
    delete from public.documents as document
    where (document.metadata ->> 'video_id')::bigint = claimed.id
      and document.metadata ->> 'ingestion_token' <> attempt_token::text;

    return query
    select
      claimed.id,
      claimed.youtube_id,
      claimed.title,
      claimed.status,
      claimed.error_message,
      claimed.created_at,
      claimed.updated_at,
      claimed.ingestion_token,
      true;
    return;
  end if;

  select video.*
  into strict claimed
  from public.videos as video
  where video.youtube_id = requested_youtube_id;

  return query
  select
    claimed.id,
    claimed.youtube_id,
    claimed.title,
    claimed.status,
    claimed.error_message,
    claimed.created_at,
    claimed.updated_at,
    claimed.ingestion_token,
    false;
end;
$function$;

create or replace function public.finalize_video_ingestion(
  target_video_id bigint,
  target_ingestion_token uuid
)
returns boolean
language plpgsql
volatile
security invoker
set search_path = ''
as $function$
declare
  current_token uuid;
begin
  select video.ingestion_token
  into current_token
  from public.videos as video
  where video.id = target_video_id
  for update;

  if current_token is distinct from target_ingestion_token then
    delete from public.documents as document
    where (document.metadata ->> 'video_id')::bigint = target_video_id
      and document.metadata ->> 'ingestion_token'
        = target_ingestion_token::text;
    return false;
  end if;

  delete from public.documents as document
  where (document.metadata ->> 'video_id')::bigint = target_video_id
    and document.metadata ->> 'ingestion_token'
      <> target_ingestion_token::text;

  update public.videos
  set
    status = 'ready',
    error_message = null,
    ingestion_token = null,
    ingestion_started_at = null,
    updated_at = now()
  where videos.id = target_video_id;

  return true;
end;
$function$;

create or replace function public.fail_video_ingestion(
  target_video_id bigint,
  target_ingestion_token uuid,
  safe_error_message text
)
returns boolean
language plpgsql
volatile
security invoker
set search_path = ''
as $function$
declare
  changed_rows integer;
begin
  delete from public.documents as document
  where (document.metadata ->> 'video_id')::bigint = target_video_id
    and document.metadata ->> 'ingestion_token'
      = target_ingestion_token::text;

  update public.videos
  set
    status = 'failed',
    error_message = left(
      coalesce(nullif(btrim(safe_error_message), ''), 'Video ingestion failed.'),
      500
    ),
    ingestion_token = null,
    ingestion_started_at = null,
    updated_at = now()
  where videos.id = target_video_id
    and videos.ingestion_token = target_ingestion_token;

  get diagnostics changed_rows = row_count;
  return changed_rows = 1;
end;
$function$;


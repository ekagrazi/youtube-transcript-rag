create or replace function public.remove_user_video(
  target_user_id uuid,
  target_video_id bigint
)
returns boolean
language plpgsql
volatile
security invoker
set search_path = ''
as $function$
declare
  changed_rows integer;
  video_status text;
begin
  select video.status
  into video_status
  from public.videos as video
  where video.id = target_video_id
  for update;

  if not found then
    return false;
  end if;

  delete from public.user_videos as membership
  where membership.user_id = target_user_id
    and membership.video_id = target_video_id;

  get diagnostics changed_rows = row_count;
  if changed_rows = 0 then
    return false;
  end if;

  if video_status <> 'pending'
    and not exists (
      select 1
      from public.user_videos as membership
      where membership.video_id = target_video_id
    )
  then
    delete from public.documents as document
    where (document.metadata ->> 'video_id')::bigint = target_video_id;

    delete from public.videos as video
    where video.id = target_video_id;
  end if;

  return true;
end;
$function$;


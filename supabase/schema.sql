-- Per-user video libraries. Transcript vectors remain shared so ingesting the
-- same YouTube video stays idempotent, while membership and chat are private.
create table if not exists public.user_videos (
  user_id uuid not null references auth.users(id) on delete cascade,
  video_id bigint not null references public.videos(id) on delete cascade,
  created_at timestamptz not null default now(),
  last_interacted_at timestamptz not null default now(),
  primary key (user_id, video_id)
);

create index if not exists user_videos_video_id_idx
  on public.user_videos (video_id);

create index if not exists user_videos_user_activity_idx
  on public.user_videos (user_id, last_interacted_at desc, video_id);

create index if not exists user_videos_last_interacted_idx
  on public.user_videos (last_interacted_at);

-- Preserve existing ownership inferred from chat history.
insert into public.user_videos (
  user_id,
  video_id,
  created_at,
  last_interacted_at
)
select
  message.user_id,
  message.video_id,
  least(min(message.created_at), min(video.created_at)),
  greatest(max(message.created_at), max(video.updated_at))
from public.chat_messages as message
join public.videos as video on video.id = message.video_id
group by message.user_id, message.video_id
on conflict (user_id, video_id) do update
set last_interacted_at = greatest(
  public.user_videos.last_interacted_at,
  excluded.last_interacted_at
);

-- On a single-user installation, retain videos that predate user libraries
-- even if that user has not chatted with them yet.
insert into public.user_videos (
  user_id,
  video_id,
  created_at,
  last_interacted_at
)
select
  sole_user.id,
  video.id,
  video.created_at,
  greatest(video.created_at, video.updated_at)
from public.videos as video
cross join lateral (
  select auth_user.id
  from auth.users as auth_user
  order by auth_user.created_at
  limit 1
) as sole_user
where (select count(*) from auth.users) = 1
  and not exists (
    select 1
    from public.user_videos as membership
    where membership.video_id = video.id
  )
on conflict (user_id, video_id) do nothing;

do $block$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'chat_messages_user_video_fkey'
      and conrelid = 'public.chat_messages'::regclass
  ) then
    alter table public.chat_messages
      add constraint chat_messages_user_video_fkey
      foreign key (user_id, video_id)
      references public.user_videos (user_id, video_id)
      on delete cascade;
  end if;
end;
$block$;

create or replace function public.add_user_video(
  target_user_id uuid,
  target_video_id bigint
)
returns table (
  library_created_at timestamptz,
  library_last_interacted_at timestamptz
)
language plpgsql
volatile
security invoker
set search_path = ''
as $function$
begin
  perform 1
  from public.videos as video
  where video.id = target_video_id
  for update;

  if not found then
    raise exception 'Video not found'
      using errcode = 'foreign_key_violation';
  end if;

  insert into public.user_videos as membership (
    user_id,
    video_id
  )
  values (
    target_user_id,
    target_video_id
  )
  on conflict (user_id, video_id) do update
  set last_interacted_at = now();

  return query
  select
    membership.created_at,
    membership.last_interacted_at
  from public.user_videos as membership
  where membership.user_id = target_user_id
    and membership.video_id = target_video_id;
end;
$function$;


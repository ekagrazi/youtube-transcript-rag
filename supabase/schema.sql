create or replace function private.cleanup_inactive_user_videos(
  retention interval default interval '7 days'
)
returns table (
  memberships_deleted bigint,
  videos_deleted bigint
)
language plpgsql
volatile
security invoker
set search_path = ''
as $function$
declare
  removed_memberships bigint;
  removed_videos bigint;
begin
  if retention < interval '1 day' then
    raise exception 'Retention must be at least one day';
  end if;

  -- Use the same video-then-membership lock order as add/remove operations.
  -- This prevents cleanup from racing a user who is adding the same video.
  perform 1
  from public.videos as video
  where not exists (
    select 1
    from public.user_videos as membership
    where membership.video_id = video.id
      and membership.last_interacted_at >= now() - retention
  )
    and (
      video.status <> 'pending'
      or video.ingestion_started_at < now() - interval '1 day'
    )
  order by video.id
  for update;

  delete from public.user_videos as membership
  where membership.last_interacted_at < now() - retention;
  get diagnostics removed_memberships = row_count;

  delete from public.documents as document
  where exists (
    select 1
    from public.videos as video
    where video.id = (document.metadata ->> 'video_id')::bigint
      and not exists (
        select 1
        from public.user_videos as membership
        where membership.video_id = video.id
      )
      and (
        video.status <> 'pending'
        or video.ingestion_started_at < now() - interval '1 day'
      )
  );

  delete from public.videos as video
  where not exists (
    select 1
    from public.user_videos as membership
    where membership.video_id = video.id
  )
    and (
      video.status <> 'pending'
      or video.ingestion_started_at < now() - interval '1 day'
    );
  get diagnostics removed_videos = row_count;

  return query select removed_memberships, removed_videos;
end;
$function$;

